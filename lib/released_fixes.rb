# frozen_string_literal: true

require 'json'
require 'open3'
require 'uri'

# Finds the open issues a published release plausibly fixed, without a model:
# issues that pull requests merged since the previous stable release close or
# mention, and issues its release notes mention. Triage then assesses each one
# against the release, and the closing policy decides whether it closes or
# proposes closing.
class ReleasedFixes
  # Each issue costs a model call, so a release settles at most this many per
  # run; a later run skips those triage already answered since the release.
  MAX_ISSUES = 10
  COMPARE_PAGES = 5
  COMMITS_PER_QUERY = 50
  FOOTER = 'Generated by [Copilot Triage]('

  def initialize(environment = ENV)
    @environment = environment
    @repository = environment.fetch('GITHUB_REPOSITORY')
    @owner, @name = @repository.split('/', 2)
    @tag = environment.fetch('TRIAGE_RELEASE').to_s.strip
    raise ArgumentError, 'a release tag is needed' if @tag.empty? || @tag.match?(/\s/)
  end

  # Returns the issues to assess, most strongly linked first, each with the
  # pull requests that reference it.
  def run
    release = api("repos/#{@repository}/releases/tags/#{URI.encode_www_form_component(@tag)}")
    if release['draft'] || release['prerelease']
      report("#{@tag} is not a stable release; nothing to settle.")
      return []
    end

    issues = candidates(release)
    report("#{@tag}: #{issues.size} open #{issues.size == 1 ? 'issue' : 'issues'} it may have fixed" \
           "#{": #{issues.map { |issue| "##{issue[:number]}" }.join(', ')}" if issues.any?}.")
    if issues.size > MAX_ISSUES
      report("Assessing the first #{MAX_ISSUES}; run it again for #{@tag} to continue.")
      issues = issues.first(MAX_ISSUES)
    end
    issues
  end

  private

  def candidates(release)
    references = Hash.new { |hash, number| hash[number] = { strength: 3, pulls: [] } }
    pulls = merged_pulls(release)
    pulls.each do |pull|
      closing = pull.dig('closingIssuesReferences', 'nodes').to_a.map { |issue| issue['number'] }
      (closing + mentions(pull['body'])).uniq.each do |number|
        entry = references[number]
        entry[:strength] = [entry[:strength], closing.include?(number) ? 1 : 2].min
        entry[:pulls] |= [pull.fetch('number')]
      end
    end
    mentions(release['body']).each { |number| references[number] }
    pull_numbers = pulls.map { |pull| pull.fetch('number') }
    references.reject! { |number, _| pull_numbers.include?(number) }
    published = release['published_at'].to_s
    found = open_issues(references.keys).reject { |issue| settled?(issue, published) }
    found.map { |issue| [issue.fetch('number'), references.fetch(issue.fetch('number'))] }
         .sort_by { |number, entry| [entry[:strength], number] }
         .map { |number, entry| { number: number, pulls: entry[:pulls].sort } }
  end

  # Pull requests merged between the previous stable release and this one.
  # Without a previous stable release, only the notes say what it fixed.
  def merged_pulls(release)
    previous = previous_stable(release)
    unless previous
      report("No stable release before #{@tag}; reading only its release notes.")
      return []
    end

    shas = commits(previous.fetch('tag_name'))
    pulls = shas.each_slice(COMMITS_PER_QUERY).flat_map do |slice|
      fields = slice.each_with_index.map do |sha, index|
        "c#{index}: object(oid: \"#{sha}\") { ... on Commit { associatedPullRequests(first: 5) { nodes { " \
          'number merged body closingIssuesReferences(first: 20) { nodes { number } } } } } }'
      end
      repository_query(fields.join("\n")).values.compact.flat_map do |commit|
        commit.dig('associatedPullRequests', 'nodes').to_a
      end
    end
    pulls.select { |pull| pull['merged'] }.uniq { |pull| pull.fetch('number') }
  end

  def previous_stable(release)
    published = release['published_at'].to_s
    api("repos/#{@repository}/releases?per_page=50")
      .reject { |candidate| candidate['draft'] || candidate['prerelease'] || candidate['tag_name'] == @tag }
      .select { |candidate| candidate['published_at'].to_s < published }
      .max_by { |candidate| candidate['published_at'].to_s }
  end

  def commits(base)
    range = "#{URI.encode_www_form_component(base)}...#{URI.encode_www_form_component(@tag)}"
    (1..COMPARE_PAGES).each_with_object([]) do |page, shas|
      batch = api("repos/#{@repository}/compare/#{range}?per_page=100&page=#{page}").fetch('commits')
      shas.concat(batch.map { |commit| commit.fetch('sha') })
      break shas if batch.size < 100
    end
  end

  # #N and links to this repository's issues, outside code.
  def mentions(text)
    prose = text.to_s.gsub(/```.*?```|`[^`]*`/m, '')
    link = %r{(?<![\w&/])\#(\d+)\b|github\.com/#{Regexp.escape(@repository)}/issues/(\d+)\b}i
    prose.scan(link).map { |short, long| Integer(short || long, 10) }.select(&:positive?).uniq
  end

  def open_issues(numbers)
    numbers.each_slice(50).flat_map do |slice|
      fields = slice.map do |number|
        "i#{number}: issueOrPullRequest(number: #{number}) { ... on Issue { number state " \
          'comments(last: 20) { nodes { createdAt body author { __typename login } } } } }'
      end
      repository_query(fields.join("\n")).values.compact.select { |issue| issue['state'] == 'OPEN' }
    end
  end

  # Triage already answered it since the release came out, such as in an
  # earlier run of this pass.
  def settled?(issue, published)
    issue.dig('comments', 'nodes').to_a.any? do |comment|
      comment['createdAt'].to_s >= published && comment['body'].to_s.include?(FOOTER)
    end
  end

  def repository_query(fields)
    query = "query($owner: String!, $name: String!) { repository(owner: $owner, name: $name) { #{fields} } }"
    graphql(query, owner: @owner, name: @name).dig('data', 'repository') || {}
  end

  def graphql(query, **variables)
    output, _errors, status = Open3.capture3({ 'GH_TOKEN' => @environment['GH_TOKEN'] }, 'gh', 'api', 'graphql',
                                             '--input', '-',
                                             stdin_data: JSON.generate(query: query, variables: variables))
    # A number that is neither an issue nor a pull request comes back as an
    # error beside the data that resolved.
    raise IOError, 'GitHub refused a query' unless status.success? || output.include?('"data"')

    JSON.parse(output)
  end

  def api(endpoint)
    output, _errors, status = Open3.capture3({ 'GH_TOKEN' => @environment['GH_TOKEN'] }, 'gh', 'api', endpoint)
    raise IOError, "GitHub refused #{endpoint}" unless status.success?

    JSON.parse(output)
  end

  def report(message)
    puts message
    summary = @environment['GITHUB_STEP_SUMMARY']
    File.open(summary, 'a') { |file| file.puts("#{message}\n\n") } if summary
  end
end

if $PROGRAM_NAME == __FILE__
  issues = begin
    ReleasedFixes.new.run
  rescue IOError, JSON::ParserError, KeyError => e
    puts "Failed: #{e.message}."
    exit 1
  end
  matrix = issues.map { |issue| { number: issue[:number].to_s, pulls: issue[:pulls].join(' ') } }
  output = ENV.fetch('GITHUB_OUTPUT', nil)
  File.open(output, 'a') { |file| file.puts("issues=#{JSON.generate(matrix)}") } if output
end
