# frozen_string_literal: true

require_relative '../lib/assessment'
require_relative 'tool_server'

# Uses fixture GitHub data and never publishes. Only live evaluations contact the model.
class EvaluationAssessment < IssueAssessment
  attr_reader :metrics, :decision, :model_responses, :tool_ledger, :copilot_debug

  def self.run(example)
    Dir.mktmpdir('triage-eval-') do |directory|
      FileUtils.cp_r(Dir.glob(File.join(__dir__, 'fixtures', '*')), directory)
      Dir.chdir(directory) do
        if example['pull_request']
          policy = YAML.safe_load_file('triage.yml').merge(
            'pull_requests' => {}, 'board' => { 'project' => 'https://github.com/users/example/projects/1' }
          )
          File.write('triage.yml', YAML.dump(policy))
        end
        assessment = new(environment_for(example), example, replay: ENV['EVAL_LIVE'] != 'true')
        assessment.run
        assessment.to_h
      end
    end
  end

  def self.environment_for(example)
    { 'GITHUB_REPOSITORY' => 'example/project', 'TRIAGE_NUMBER' => '100', 'TRIAGE_CONFIG' => 'triage.yml',
      'TRIAGE_DRY_RUN' => 'true', 'TRIAGE_DEBOUNCE_SECONDS' => '0', 'TRIAGE_STATE_DIR' => 'state',
      'TRIAGE_DEBUG' => 'true', 'TRIAGE_MODEL' => ENV.fetch('TRIAGE_MODEL', 'gpt-5.6-luna'),
      'TRIAGE_REASONING_EFFORT' => ENV.fetch('TRIAGE_REASONING_EFFORT', 'low'),
      'COPILOT_GITHUB_TOKEN' => ENV.fetch('COPILOT_GITHUB_TOKEN', nil),
      'TRIAGE_ENGINE' => ENV.fetch('TRIAGE_ENGINE', 'copilot'), 'TRIAGE_PROVIDER' => ENV.fetch('TRIAGE_PROVIDER', nil),
      'TRIAGE_API_KEY' => ENV.fetch('TRIAGE_API_KEY', nil), 'TRIAGE_API_BASE' => ENV.fetch('TRIAGE_API_BASE', nil),
      'TRIAGE_KIND' => example['pull_request'] ? 'pull_request' : 'issue',
      'GITHUB_EVENT_NAME' => if example['pull_request'] then 'pull_request_review'
                             elsif example['comment'] then 'issue_comment'
                             else 'issues'
                             end,
      'GITHUB_EVENT_PATH' => 'fixture-event' }
  end

  def initialize(environment, example, replay:)
    super(environment)
    @example = example
    @replay = replay
    @model_responses = []
  end

  def to_h
    action = { 'reply' => 'reply', 'duplicate_closed' => 'duplicate' }.fetch(metrics.fetch('outcome'), 'silent')
    action = 'error' if metrics['outcome'] == 'error' || metrics['reason'].to_s.match?(/invalid|unavailable|exhausted/)
    { action:, reply: decision && reply_body(decision), decision:, metrics:, model_responses:,
      tool_calls: tool_ledger.fetch('trace', []), copilot_debug:,
      mode: @replay ? 'offline_replay' : 'live' }
  end

  private

  def assess(item, labels)
    @decision = super
  end

  def ask_model(prompt)
    response = if @replay
                 @example.fetch('tools', []).each do |call|
                   result = evidence_tools.call(call.fetch('name'), call.fetch('arguments'))
                   raise result.inspect if result[:isError]
                 end
                 result = evidence_tools.call('submit_decision', @example.fetch('decision'))
                 raise result.inspect if result[:isError]

                 @tool_ledger = evidence_tools.ledger
                 JSON.generate(@tool_ledger.fetch('decision'))
               else
                 super
               end
    @model_responses << response
    response
  end

  def tools_settings(directory)
    super.merge(example: @example)
  end

  def engine_tools(settings)
    EvaluationTools.new(**settings)
  end

  def tools_command(settings_path)
    [RbConfig.ruby, File.join(__dir__, 'tool_server.rb'), settings_path]
  end

  def evidence_tools
    @evidence_tools ||= EvaluationTools.new(root: Dir.pwd, repository: @repository, config: @config, example: @example,
                                            pull_request: (if pull_request?
                                                             @number
                                                           end), **schema_options.slice(:board, :move))
  end

  def read_report
    return pull_request_report if @example['pull_request']

    comments = []
    if @example['previous_question']
      comments << { 'id' => 'bot-1', 'author' => { '__typename' => 'Bot', 'login' => 'github-actions' },
                    'body' => "#{@example['previous_question']}\n\n_Generated by [Copilot Triage](link)._" }
    end
    comments << human_comment if @example['comment']
    [{ 'id' => 'issue-100', 'title' => @example.fetch('title'), 'body' => @example.fetch('body'), 'closed' => false,
       'author' => { 'login' => 'reporter' }, 'comments' => { 'nodes' => comments } },
     @config.fetch('labels').keys.map { |name| { 'id' => name, 'name' => name } }]
  end

  # A real pull request with Copilot's last review on its latest commit, as a
  # review event delivers it.
  def pull_request_report
    pull = @example.fetch('pull_request')
    files = pull.fetch('files')
    review = { 'author' => { 'login' => 'copilot-pull-request-reviewer' }, 'state' => 'COMMENTED',
               'body' => pull.fetch('copilot_review'), 'submittedAt' => '2026-10-01T10:00:00Z',
               'commit' => { 'oid' => 'head' } }
    [{ 'id' => 'pr-100', 'title' => @example.fetch('title'), 'body' => @example.fetch('body'), 'closed' => false,
       'author' => { 'login' => 'author' }, 'authorAssociation' => pull.fetch('association'), 'isDraft' => false,
       'headRefOid' => 'head', 'changedFiles' => files.size, 'additions' => files.sum { |file| file['additions'] },
       'deletions' => files.sum { |file| file['deletions'] }, 'files' => { 'nodes' => files },
       'reviews' => { 'nodes' => [review] }, 'reviewRequests' => { 'nodes' => [] },
       'assignees' => { 'totalCount' => 0 }, 'comments' => { 'nodes' => [] } },
     @config.fetch('labels').keys.map { |name| { 'id' => name, 'name' => name } }]
  end

  def human_comment
    { 'id' => 'human-1', 'body' => @example.fetch('comment'),
      'author' => { '__typename' => 'User', 'login' => 'reporter' }, 'authorAssociation' => 'NONE' }
  end

  def event
    if @example['pull_request']
      return { 'action' => 'submitted', 'repository' => { 'full_name' => 'example/project' },
               'review' => { 'user' => { 'login' => 'copilot-pull-request-reviewer[bot]' } },
               'pull_request' => { 'number' => 100, 'head' => { 'repo' => { 'full_name' => 'example/project' } } } }
    end

    { 'action' => @example['comment'] ? 'created' : 'opened',
      'sender' => { 'type' => 'User' }, 'issue' => { 'state' => 'open' },
      'comment' => { 'node_id' => 'human-1', 'body' => @example['comment'],
                     'user' => { 'type' => 'User' }, 'author_association' => 'NONE' } }
  end

  def github(*)
    raise 'Evaluation attempted a GitHub request'
  end

  def source_url(path)
    "https://example.invalid/#{path}"
  end

  def report(message)
    @copilot_debug = JSON.parse(message.delete_prefix('Triage debug: ')) if message.start_with?('Triage debug: ')
    return unless message.start_with?('Triage metrics: ')

    @metrics = JSON.parse(message.delete_prefix('Triage metrics: '))
  end
end
