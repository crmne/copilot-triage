# frozen_string_literal: true

require 'optparse'
require_relative '../lib/assessment'

# Uses fixture GitHub data and never publishes. Only --live contacts the model.
class TriageEvaluation < IssueAssessment
  attr_reader :metrics, :decision, :model_responses

  def initialize(environment, example, replay:)
    super(environment)
    @example = example
    @replay = replay
    @responses = example.fetch('replay').map { |value| JSON.generate(value) }
    @model_responses = []
  end

  private

  def assess(item, labels)
    @decision = super
  end

  def ask_copilot(prompt)
    response = @replay ? @responses.shift || raise('Replay exhausted: unexpected model call') : super
    @model_responses << response
    response
  end

  def read_report
    comments = []
    if @example['previous_question']
      comments << { 'id' => 'bot-1', 'author' => { '__typename' => 'Bot', 'login' => 'github-actions' },
                    'body' => "#{@example['previous_question']}\n\n_Generated by [Copilot Triage](link)._" }
    end
    comments << human_comment if @example['comment']
    [{ 'id' => 'issue-100', 'title' => @example.fetch('title'), 'body' => @example.fetch('body'), 'closed' => false,
       'author' => { 'login' => 'reporter' }, 'comments' => { 'nodes' => comments } },
     @config.fetch('labels').keys.map { |name| { 'id' => name, 'name' => name } }]
  end

  def human_comment
    { 'id' => 'human-1', 'body' => @example.fetch('comment'),
      'author' => { '__typename' => 'User', 'login' => 'reporter' }, 'authorAssociation' => 'NONE' }
  end

  def event
    { 'action' => @example['comment'] ? 'created' : 'opened',
      'sender' => { 'type' => 'User' }, 'issue' => { 'state' => 'open' },
      'comment' => { 'node_id' => 'human-1', 'body' => @example['comment'],
                     'user' => { 'type' => 'User' }, 'author_association' => 'NONE' } }
  end

  def github(_endpoint, query:, variables:)
    raise 'Evaluation attempted a GitHub mutation' if query.start_with?('mutation')

    data = if variables.key?(:ids)
             { 'nodes' => [@example['release']].compact }
           elsif query.include?('releases(first:')
             { 'repository' => { 'releases' => { 'nodes' => [@example['release']].compact } } }
           elsif query.include?('issues(first:')
             candidates = query.include?('CLOSED') ? [] : [@example['candidate']].compact
             { 'repository' => { 'issues' => { 'nodes' => candidates } } }
           else
             { 'repository' => { 'issue' => @example.fetch('candidate') } }
           end
    JSON.parse(JSON.generate({ 'data' => data }))
  end

  def source_url(path)
    "https://example.invalid/#{path}"
  end

  def report(message)
    return unless message.start_with?('Triage metrics: ')

    @metrics = JSON.parse(message.delete_prefix('Triage metrics: '))
  end
end

options = { replay: true, model: 'gpt-5.6-luna', effort: 'low' }
OptionParser.new do |parser|
  parser.banner = 'Usage: ruby eval/run.rb [--replay | --live] [--model ID] [--case ID] [--output PATH]'
  parser.on('--replay', 'Offline replay; no model credits (default)') { options[:replay] = true }
  parser.on('--live', 'Evaluate fresh model output using COPILOT_GITHUB_TOKEN') { options[:replay] = false }
  parser.on('--model ID') { |value| options[:model] = value }
  parser.on('--reasoning-effort EFFORT', %w[none low]) { |value| options[:effort] = value }
  parser.on('--case ID') { |value| options[:case] = value }
  parser.on('--output PATH') { |value| options[:output] = value }
end.parse!
abort 'Set COPILOT_GITHUB_TOKEN for live evaluation.' unless options[:replay] || ENV['COPILOT_GITHUB_TOKEN']

cases = YAML.safe_load_file(File.join(__dir__, 'cases.yml'))
cases.select! { |example| example.fetch('id') == options[:case] } if options[:case]
abort 'No matching evaluation cases.' if cases.empty?
results = cases.map do |example|
  Dir.mktmpdir('triage-eval-') do |directory|
    FileUtils.cp_r(Dir.glob(File.join(__dir__, 'fixtures', '*')), directory)
    Dir.chdir(directory) do
      environment = { 'GITHUB_REPOSITORY' => 'example/project', 'TRIAGE_NUMBER' => '100',
                      'TRIAGE_CONFIG' => 'triage.yml',
                      'TRIAGE_DRY_RUN' => 'true', 'TRIAGE_DEBOUNCE_SECONDS' => '0', 'TRIAGE_STATE_DIR' => 'state',
                      'TRIAGE_MODEL' => options[:model],
                      'TRIAGE_REASONING_EFFORT' => options[:effort],
                      'COPILOT_GITHUB_TOKEN' => ENV.fetch('COPILOT_GITHUB_TOKEN', nil),
                      'GITHUB_EVENT_NAME' => example['comment'] ? 'issue_comment' : 'issues',
                      'GITHUB_EVENT_PATH' => 'fixture-event' }
      runner = TriageEvaluation.new(environment, example, replay: options[:replay])
      runner.run
      metrics = runner.metrics
      body = runner.decision && runner.send(:reply_body, runner.decision)
      action = { 'reply' => 'reply', 'duplicate_closed' => 'duplicate' }.fetch(metrics.fetch('outcome'), 'silent')
      if metrics['outcome'] == 'error' || metrics['reason'].to_s.match?(/invalid|unavailable|exhausted/)
        action = 'error'
      end
      expected = example.fetch('expected')
      content = body.to_s.downcase
      alternatives = expected.fetch('contains_any', [])
      actions = expected.fetch('allowed_actions', [expected.fetch('action')])
      passed = actions.include?(action) && metrics.fetch('model_calls') <= expected.fetch('max_calls') &&
               metrics.fetch('model_calls') >= expected.fetch('min_calls', 0) &&
               (action == 'silent' || expected.fetch('contains', []).all? do |text|
                 content.include?(text.to_s.downcase)
               end) &&
               (alternatives.empty? || alternatives.any? { |text| content.include?(text.to_s.downcase) })
      { id: example.fetch('id'), passed: passed, expected: expected['action'], allowed_actions: actions, actual: action,
        reply: body, metrics: metrics, model_responses: runner.model_responses }
    end
  end
end
summary = {
  mode: options[:replay] ? 'offline_replay' : 'live', model: options[:model], reasoning_effort: options[:effort],
  cases: results.size,
  passed: results.count { |result| result[:passed] },
  unnecessary_replies: results.count do |result|
    !result[:allowed_actions].include?(result[:actual]) && %w[reply duplicate].include?(result[:actual])
  end,
  missed_helpful_replies: results.count do |result|
    !result[:allowed_actions].include?('silent') && result[:actual] == 'silent'
  end,
  model_calls: results.sum { |result| result[:metrics].fetch('model_calls') },
  prompt_bytes: results.sum { |result| result[:metrics].fetch('prompt_bytes') },
  elapsed_seconds: results.sum { |result| result[:metrics].fetch('elapsed_seconds') }.round(3),
  results: results
}
output = JSON.pretty_generate(summary)
options[:output] ? File.write(options[:output], "#{output}\n") : puts(output)
exit(results.all? { |result| result[:passed] } ? 0 : 1)
