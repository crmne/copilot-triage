require_relative '../lib/assessment'

RSpec.describe 'Reply guards' do
  let(:config) { YAML.safe_load_file('triage.yml') }
  let(:environment) do
    { 'GITHUB_REPOSITORY' => 'crmne/example', 'TRIAGE_NUMBER' => '1', 'TRIAGE_CONFIG' => 'triage.yml',
      'GITHUB_STEP_SUMMARY' => 'summary.md' }
  end
  let(:assessment) { IssueAssessment.new(environment) }
  let(:item) do
    { 'id' => 'report-id', 'title' => 'Playback pauses at random', 'body' => 'Playback pauses every few minutes.',
      'closed' => false, 'author' => { '__typename' => 'User', 'login' => 'reporter' },
      'comments' => { 'nodes' => [] } }
  end
  let(:labels) { [{ 'id' => 'bug-id', 'name' => 'bug' }] }

  before do
    File.write('triage.yml', config.to_yaml)
    allow(assessment).to receive_messages(read_report: [item, labels])
    allow(assessment).to receive(:mutate)
    allow(assessment).to receive(:puts)
  end

  def decide(comment, **decision)
    allow(assessment).to receive(:ask_copilot).and_return(
      JSON.generate({ labels: ['bug'], reply: nil, sources: [], comment: comment }.merge(decision))
    )
  end

  [
    'The log shows audio underruns; please investigate this as a playback bug.',
    'Confirmed: the cache is cleared before the write finishes.',
    'This is a scoped enhancement that needs a product decision.',
    'This is a distinct enhancement for maintainer prioritization.',
    'The reporter found a confirmed playback bug in the queue.'
  ].each do |comment|
    it "keeps quiet instead of posting #{comment.inspect}" do
      decide(comment)

      assessment.run

      expect(assessment).not_to be_failed
      expect(assessment).to have_received(:mutate).with('addLabelsToLabelable', labelableId: 'report-id',
                                                                                labelIds: ['bug-id'])
      expect(assessment).not_to have_received(:mutate).with('addComment', anything)
      expect(File.read('summary.md')).to include('Dropped the reply: it was addressed to the maintainer.')
    end
  end

  context 'with a follow-up comment' do
    let(:board) { instance_double(ProjectBoard, update: { 'column' => 'Decide' }) }
    let(:latest) { thread_comment('human-latest', 'The command printed nothing at all.') }
    let(:event) do
      { 'action' => 'created', 'sender' => { 'login' => 'reporter', 'type' => 'User' },
        'issue' => { 'number' => 1, 'state' => 'open' },
        'comment' => { 'node_id' => 'human-latest', 'body' => latest['body'],
                       'user' => { 'login' => 'reporter', 'type' => 'User' }, 'author_association' => 'NONE' } }
    end

    def thread_comment(id, body, bot: false, association: 'NONE')
      author = bot ? { '__typename' => 'Bot', 'login' => 'github-actions' } : { '__typename' => 'User', 'login' => id }
      body = "#{body}\n\n_Generated by [Copilot Triage](https://github.com/marketplace/actions/copilot-triage)._" if bot
      { 'id' => id, 'body' => body, 'author' => author, 'authorAssociation' => association }
    end

    def thread(*comments)
      item['comments']['nodes'] = [*comments, latest]
    end

    let(:config) { super().merge('board' => { 'project' => 'https://github.com/users/crmne/projects/3' }) }

    before do
      environment.merge!('GITHUB_EVENT_NAME' => 'issue_comment', 'GITHUB_EVENT_PATH' => 'event.json',
                         'TRIAGE_PROJECT_TOKEN' => 'project-token')
      allow(assessment).to receive_messages(event: event, board: board)
      allow(assessment).to receive(:sleep)
      decide('Which exact command did you run?', next_move: 'theirs', priority: 'normal',
                                                 next_step: 'Wait for the reporter.')
    end

    it 'keeps quiet after two replies since a maintainer last commented, and leaves the card to decide' do
      thread(thread_comment('maintainer', 'Can you share the log?', association: 'OWNER'),
             thread_comment('bot-1', 'What is the SHA-256 of the file?', bot: true),
             thread_comment('reporter-1', 'Not sure what you mean.'),
             thread_comment('bot-2', 'Run Get-FileHash on the file.', bot: true))

      assessment.run

      expect(assessment).not_to be_failed
      expect(assessment).to have_received(:ask_copilot).with(
        include('Triage replies since a maintainer last commented: 2 of at most 2.')
      )
      expect(assessment).to have_received(:mutate).with('addLabelsToLabelable', anything)
      expect(assessment).not_to have_received(:mutate).with('addComment', anything)
      expect(board).to have_received(:update).with('report-id', hash_including(column: 'decide'))
      expect(File.read('summary.md')).to include('Dropped the reply: triage replied 2 times')
    end

    it 'counts only replies after the latest maintainer comment' do
      thread(thread_comment('bot-1', 'What is the SHA-256 of the file?', bot: true),
             thread_comment('bot-2', 'Run Get-FileHash on the file.', bot: true),
             thread_comment('maintainer', 'That is SmartScreen; choose More info, then Run anyway.',
                            association: 'OWNER'),
             thread_comment('bot-3', 'Does Run anyway appear?', bot: true))

      assessment.run

      expect(assessment).to have_received(:ask_copilot).with(
        include('Triage replies since a maintainer last commented: 1 of at most 2.')
      )
      expect(assessment).to have_received(:mutate).with('addComment', subjectId: 'report-id',
                                                                      body: start_with('Which exact command'))
    end
  end

  it 'still tells a contributor that a new setting needs maintainer approval' do
    comment = 'A new setting needs maintainer approval in the issue before a pull request.'
    decide(comment)

    assessment.run

    expect(assessment).to have_received(:mutate).with('addComment', subjectId: 'report-id',
                                                                    body: start_with(comment))
  end
end

RSpec.describe 'Links the conversation already has' do
  let(:environment) do
    { 'GITHUB_REPOSITORY' => 'owner/project', 'TRIAGE_NUMBER' => '123', 'TRIAGE_KIND' => 'issue',
      'TRIAGE_CONFIG' => 'triage.yml' }
  end
  let(:assessment) { IssueAssessment.new(environment) }
  let(:item) do
    { 'id' => 'current-id', 'title' => 'Remember the theme', 'body' => 'The theme resets after restarting.',
      'closed' => false, 'authorAssociation' => 'NONE', 'author' => { 'login' => 'reporter' },
      'comments' => { 'nodes' => [] } }
  end
  let(:candidate) do
    { 'node_id' => 'candidate-id', 'number' => 42, 'title' => 'Persist theme across restarts',
      'body' => 'The selected theme resets each time I restart.', 'state' => 'open', 'comments' => 0,
      'html_url' => 'https://github.com/owner/project/issues/42' }
  end
  let(:decision) do
    { labels: [], reply: nil, sources: [], related_issue: 42, relationship: 'related',
      comment: 'Both reports describe the selected theme resetting after a restart.' }
  end
  let(:policy) { {} }

  before do
    policy = YAML.safe_load_file('triage.yml').merge('duplicates' => 'suggest').merge(self.policy)
    File.write('triage.yml', YAML.dump(policy))
    allow(assessment).to receive_messages(read_report: [item, []], puts: nil, mutate: nil)
    allow(assessment.send(:evidence_tools)).to receive(:api) { Marshal.load(Marshal.dump(candidate)) }
    allow(assessment).to receive(:ask_copilot) do
      agent_reads(assessment, 'issue:42', *decision[:sources])
      JSON.generate(decision)
    end
  end

  {
    'the report' => ->(report) { report['body'] += ' Maybe related to #42.' },
    'a comment' => lambda { |report|
      report['comments']['nodes'] << { 'body' => 'See https://github.com/owner/project/issues/42 too.',
                                       'author' => { 'login' => 'helper' }, 'authorAssociation' => 'NONE' }
    }
  }.each do |where, change|
    it "keeps quiet about a related issue #{where} already links" do
      change.call(item)

      assessment.run

      expect(assessment).not_to be_failed
      expect(assessment).not_to have_received(:mutate).with('addComment', anything)
    end
  end

  it 'does not repeat its own earlier link, even as a duplicate' do
    decision[:relationship] = 'duplicate'
    item['comments']['nodes'] << { 'body' => "See also #42.\n\n_Generated by [Copilot Triage](link)._",
                                   'author' => { '__typename' => 'Bot', 'login' => 'github-actions' } }
    item['comments']['nodes'] << { 'body' => 'Still happens.', 'author' => { 'login' => 'reporter' },
                                   'authorAssociation' => 'NONE' }

    assessment.run

    expect(assessment).not_to have_received(:mutate).with('addComment', anything)
  end

  it 'still confirms a duplicate the reporter only suspected' do
    decision[:relationship] = 'duplicate'
    item['body'] += ' This might be #42 again.'

    assessment.run

    expect(assessment).to have_received(:mutate).with('addComment', hash_including(body: start_with('See also #42.')))
  end

  it 'links an issue whose number only appears inside another number or repository' do
    item['body'] += ' It started after #420 and other/project#42.'

    assessment.run

    expect(assessment).to have_received(:mutate).with('addComment', hash_including(body: start_with('See also #42.')))
  end

  context 'with cited facts' do
    let(:policy) { { 'sources' => ['docs/*.md'] } }

    it 'keeps the comment but drops the link' do
      File.write('docs/theme.md', 'The theme is saved when the window closes.')
      allow(Open3).to receive(:capture2).and_return(['a' * 40, instance_double(Process::Status, success?: true)])
      item['body'] += ' Like #42.'
      decision.merge!(sources: ['file:docs/theme.md'], comment: 'The theme is saved on close, [[file:docs/theme.md]].')

      assessment.run

      expect(assessment).to have_received(:mutate).with('addComment',
                                                        hash_including(body: start_with('The theme is saved')))
    end
  end

  context 'with a pull request' do
    let(:environment) { super().merge('TRIAGE_KIND' => 'pull_request') }
    let(:policy) { { 'pull_requests' => {} } }

    it 'does not link the issue the pull request already closes' do
      item.merge!('body' => 'Fixes #42.', 'isDraft' => false, 'files' => { 'nodes' => [] }, 'changedFiles' => 0,
                  'additions' => 0, 'deletions' => 0)
      decision.merge!(review: false, out_of_scope: false)

      assessment.run

      expect(assessment).not_to be_failed
      expect(assessment).not_to have_received(:mutate).with('addComment', anything)
    end
  end
end

RSpec.describe TriageTools, 'citing the report itself' do
  let(:config) { { 'labels' => { 'bug' => 'A bug.' }, 'replies' => {} } }
  let(:tools) { described_class.new(root: Dir.pwd, repository: 'owner/project', config: config, number: 7) }

  it 'asks the agent to cite other evidence' do
    tools.ledger['evidence']['issue:7'] = { 'complete' => true }
    result = tools.call('submit_decision', { 'labels' => [], 'reply' => nil, 'sources' => ['issue:7'],
                                             'comment' => 'As this report says, see [[issue:7]].',
                                             'related_issue' => nil, 'relationship' => nil, 'mute' => false })

    expect(result[:isError]).to be(true)
    expect(result.dig(:content, 0, :text)).to include('issue:7 is this report itself')
    expect(tools.ledger).not_to have_key('decision')
  end
end
