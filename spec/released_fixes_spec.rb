# frozen_string_literal: true

require 'yaml'
require_relative '../lib/released_fixes'

RSpec.describe ReleasedFixes do
  let(:environment) { { 'GITHUB_REPOSITORY' => 'crmne/zapfast', 'TRIAGE_RELEASE' => 'v0.20.1' } }
  let(:finder) { described_class.new(environment) }
  let(:release) do
    { 'tag_name' => 'v0.20.1', 'prerelease' => false, 'draft' => false, 'published_at' => '2026-10-20T10:00:00Z',
      'body' => "Fixes the tray icon (#510).\n\n```\nlog line #999\n```" }
  end
  let(:releases) do
    [release,
     { 'tag_name' => 'v0.21.0-beta.1', 'prerelease' => true, 'published_at' => '2026-10-19T00:00:00Z' },
     { 'tag_name' => 'v0.20.0', 'prerelease' => false, 'published_at' => '2026-10-01T00:00:00Z' },
     { 'tag_name' => 'v0.19.0', 'prerelease' => false, 'published_at' => '2026-09-01T00:00:00Z' }]
  end
  let(:pulls) do
    { 'aaa' => [{ 'number' => 370, 'merged' => true, 'body' => 'Rework playback. Also helps #564.',
                  'closingIssuesReferences' => { 'nodes' => [{ 'number' => 534 }] } }],
      'bbb' => [{ 'number' => 380, 'merged' => true, 'body' => 'See #370 and #392.',
                  'closingIssuesReferences' => { 'nodes' => [] } },
                { 'number' => 381, 'merged' => false, 'body' => 'Closes #700',
                  'closingIssuesReferences' => { 'nodes' => [{ 'number' => 700 }] } }] }
  end
  let(:footer) { 'Generated by [Copilot Triage](https://github.com/crmne/copilot-triage)' }
  let(:issues) do
    { 510 => { 'state' => 'OPEN' }, 534 => { 'state' => 'OPEN' }, 564 => { 'state' => 'OPEN' },
      392 => { 'state' => 'CLOSED' }, 700 => { 'state' => 'OPEN' } }
  end
  let(:compared) { [] }

  before do
    allow(finder).to receive(:puts)
    allow(finder).to receive(:api) do |endpoint|
      case endpoint
      when %r{/releases/tags/} then release
      when /releases\?/ then releases
      when %r{/compare/}
        compared << endpoint
        { 'commits' => [{ 'sha' => 'aaa' }, { 'sha' => 'bbb' }] }
      end
    end
    allow(finder).to receive(:graphql) do |query, **_variables|
      nodes = if query.include?('associatedPullRequests')
                query.scan(/(c\d+): object\(oid: "(\w+)"\)/).to_h do |field, sha|
                  [field, { 'associatedPullRequests' => { 'nodes' => pulls.fetch(sha, []) } }]
                end
              else
                query.scan(/i(\d+): issueOrPullRequest/).flatten.to_h do |number|
                  issue = issues[Integer(number)]
                  ["i#{number}", issue && { 'number' => Integer(number), 'comments' => { 'nodes' => [] } }.merge(issue)]
                end
              end
      { 'data' => { 'repository' => nodes } }
    end
  end

  it 'finds open issues closed by, mentioned in, or named in the notes of what merged since the last stable release' do
    expect(finder.run).to eq([{ number: 534, pulls: [370] }, { number: 564, pulls: [370] },
                              { number: 510, pulls: [] }])
    expect(compared).to eq(['repos/crmne/zapfast/compare/v0.20.0...v0.20.1?per_page=100&page=1'])
  end

  it 'skips issues triage already answered since the release' do
    issues[534]['comments'] = { 'nodes' => [{ 'createdAt' => '2026-10-21T00:00:00Z', 'body' => "Fixed.\n#{footer}" }] }
    issues[564]['comments'] = { 'nodes' => [{ 'createdAt' => '2026-10-01T00:00:00Z', 'body' => "Hm.\n#{footer}" }] }

    expect(finder.run.map { |issue| issue[:number] }).to eq([564, 510])
  end

  it 'caps how many issues one run assesses' do
    release['body'] = (1..(described_class::MAX_ISSUES + 3)).map { |number| "##{number + 1000}" }.join(' ')
    (1001..1013).each { |number| issues[number] = { 'state' => 'OPEN' } }

    found = finder.run
    expect(found.size).to eq(described_class::MAX_ISSUES)
    expect(found.first).to eq(number: 534, pulls: [370])
    expect(finder).to have_received(:puts).with(/run it again for v0.20.1/)
  end

  it 'reads only the notes of the first stable release' do
    releases.replace([release])

    expect(finder.run).to eq([{ number: 510, pulls: [] }])
    expect(compared).to be_empty
  end

  it 'settles nothing for a prerelease' do
    release['prerelease'] = true

    expect(finder.run).to eq([])
  end

  it 'needs a tag' do
    expect { described_class.new(environment.merge('TRIAGE_RELEASE' => ' ')) }.to raise_error(ArgumentError)
  end
end

RSpec.describe 'the shared release workflow' do
  let(:workflow) { YAML.load_file(File.expand_path('../.github/workflows/settle.yml', __dir__)) }

  it 'assesses each issue it finds as an ordinary report, checked against the release' do
    step = workflow.dig('jobs', 'assess', 'steps', 0, 'with')

    expect(workflow.dig('jobs', 'find', 'steps', 0, 'with', 'mode')).to eq('release')
    expect(step).to include('kind' => 'issue', 'number' => '${{ matrix.number }}', 'release' => '${{ inputs.tag }}',
                            'release-pulls' => '${{ matrix.pulls }}')
    expect(workflow.dig('jobs', 'assess', 'concurrency', 'group')).to eq('assessment-issue-${{ matrix.number }}-report')
    expect(workflow.dig('jobs', 'assess', 'cache-mode')).to eq('write')
  end
end
